import { MAX_WIND, windDirection, windMagnitude } from './wind';

/**
 * Флажок на башне своего танка (#550, §7 разбора #534): «дешёвый носитель» ветра
 * рядом с ареной, куда и так смотрит взгляд во время прицеливания — не только цифра
 * в ячейке «Ветер» наверху HUD. Модель чистая: угол поворота считается от `wind`
 * теми же `windDirection`/`windMagnitude`, что дают знак и пипы ячейки «Ветер»
 * (`wind.ts`) — флажок и HUD не могут разойтись в показаниях.
 */

/**
 * Канонический размер флажка (CSS px, `scale === 1`) — Issue #550, пересмотрен в #579.
 *
 * Имена — по осям контура полотнища, а не по осям экрана (ревью #579): `LENGTH` —
 * длина от мачты до свободного края (протяжённость вдоль локального `x`),
 * `THICKNESS` — толщина у мачты (разброс по локальному `y`). Прежние
 * `WIND_FLAG_HEIGHT`/`WIND_FLAG_WIDTH` достались от `fillRect` и означали ровно
 * противоположное осям, из-за чего `{ x: HEIGHT, y: WIDTH / 2 }` в контуре читалось
 * как опечатка.
 *
 * Мачта **выше длины полотнища**: в штиль вымпел виснет вдоль неё вниз ровно на свою
 * длину, и разница `POLE_HEIGHT - LENGTH` — гарантированный зазор между концом
 * полотнища и верхом корпуса. Без него флаг лежал на башне и читался как приклеенный
 * к корпусу прямоугольник (замечание с прода 14.08.2026). Зазор — 3 единицы, а не 2:
 * обводка полотнища (`max(1, flagScale)` px) рисуется ПО ЦЕНТРУ контура и съедает
 * половину своей ширины из просвета (ревью #579 — на арене 1440 оставалось ≈2px).
 */
export const WIND_FLAG_THICKNESS = 8;
export const WIND_FLAG_LENGTH = 14;
export const WIND_FLAG_POLE_HEIGHT = 17;
/** Толщина мачты: не «волосок в один пиксель», иначе древка не видно и флага не читается. */
export const WIND_FLAG_POLE_WIDTH = 2;

/**
 * Пол масштаба флажка (#579). Флажок — не часть корпуса, а ЗНАК: на узкой арене
 * (`WORLD_SCALE_MIN` = 0.5) честно масштабированный вымпел ужимался в 7×4 px, где
 * пиксель обводки съедал форму и оставалось тёмное пятнышко. Ниже этого коэффициента
 * флажок не уменьшается — тот же приём, что уже применён к толщине мачты
 * (`Math.max(2, …)`) и к тени корпуса, только для всей фигуры целиком.
 */
export const WIND_FLAG_MIN_SCALE = 0.8;

/** Доля толщины полотнища у свободного края — сужение вымпела к концу. */
const FLY_TAPER = 0.55;
/** Глубина выреза «ласточкин хвост» как доля длины полотнища. */
const NOTCH_DEPTH = 0.3;

/**
 * Контур вымпела в МИРОВЫХ единицах (`scale === 1`), локальная система полотнища:
 * начало — вершина мачты, полотнище уходит вдоль `+x` и висит по ОДНУ сторону от оси
 * (`y` от 0 до `WIDTH`), как настоящий флаг на древке. Симметричная относительно оси
 * лента была хуже: в штиль она садилась вокруг мачты, светлое ядро древка резало её
 * пополам, и вместо флага читалась полосатая бирка.
 *
 * Рендер умножает точки на текущий `scale`, зеркалит их по знаку ветра
 * (`Tank.drawWindFlag`, чтобы полотнище всегда провисало ПОД осью, а не задиралось
 * вверх против ветра) и рисует в системе, уже повёрнутой на `windFlagRotationRad`, —
 * угол наклона остаётся чистой моделью ветра (#550), а форма живёт здесь.
 *
 * Форма (#579): сужение к свободному краю плюс треугольный вырез — то, чем вымпел
 * отличается от прямоугольника, которым флажок был раньше. Константа, а не функция:
 * `Tank.draw` зовётся каждый кадр, и правило `canvas.md` запрещает аллокации в кадре.
 */
export const WIND_FLAG_PENNANT: readonly { x: number; y: number }[] = [
    { x: 0, y: 0 },
    { x: WIND_FLAG_LENGTH, y: (WIND_FLAG_THICKNESS * (1 - FLY_TAPER)) / 2 },
    { x: WIND_FLAG_LENGTH * (1 - NOTCH_DEPTH), y: WIND_FLAG_THICKNESS / 2 },
    { x: WIND_FLAG_LENGTH, y: (WIND_FLAG_THICKNESS * (1 + FLY_TAPER)) / 2 },
    { x: 0, y: WIND_FLAG_THICKNESS },
];

/**
 * Наклон флажка (градусы) от нейтрали по силе ветра (0..3 пипа шкалы HUD,
 * `WIND_DISPLAY_SCALE`) — три положения на сторону при магнитуде 1..3, индекс 0 —
 * штиль (наклона нет).
 */
const LEAN_DEG_BY_MAGNITUDE: readonly number[] = [0, 20, 40, 60];

/**
 * Угол поворота флажка в радианах для `ctx.rotate` вокруг вершины мачты. `90°`
 * (`Math.PI / 2`) — флажок висит вдоль мачты вниз: нейтраль на `wind = 0` (критерий
 * #550). С ростом силы ветра угол уходит к горизонтали — вправо (`< 90°`) при
 * `windDirection === 'right'`, влево (`> 90°`) при `'left'`, зеркально относительно
 * нейтрали при равной по модулю силе ветра разного знака.
 */
export function windFlagRotationRad(wind: number, maxWind = MAX_WIND): number {
    const magnitude = windMagnitude(wind, maxWind);
    const lean = LEAN_DEG_BY_MAGNITUDE[Math.min(magnitude, LEAN_DEG_BY_MAGNITUDE.length - 1)];
    const restDeg = 90;
    const rotatedDeg = windDirection(wind) === 'right' ? restDeg - lean : restDeg + lean;
    return (rotatedDeg * Math.PI) / 180;
}

/**
 * Сторона, в которую провисает односторонний вымпел: `1` — полотнище уходит от оси
 * мачты вниз-вправо (ветер вправо, нейтраль), `-1` — зеркально (ветер влево).
 * Иначе левый флаг задирался бы вверх против ветра, и левый перестал бы быть
 * отражением правого.
 *
 * Выводится из ЗНАКА ветра теми же `windDirection`, что и угол, — а не из самого
 * угла (ревью #579). Порог «угол > 90°» сегодня совпадает с направлением только
 * потому, что наклон не превышает 60°: вырасти `LEAN_DEG_BY_MAGNITUDE` до 90°+ или
 * сменись нейтраль — зеркало перевернулось бы молча, и форма разошлась бы с моделью.
 */
export function windFlagSide(wind: number): 1 | -1 {
    return windDirection(wind) === 'right' ? 1 : -1;
}
