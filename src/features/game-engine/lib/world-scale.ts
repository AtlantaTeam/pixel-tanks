/**
 * Масштаб мира от ширины арены (issue #455).
 *
 * Размеры объектов раньше были прошиты в пикселях (`Tank`: 60×30, ствол 35×5,
 * снаряд r=2, взрыв r=50). На узком экране (390 px) танк занимал 15% ширины —
 * выглядел огромным; на широком (1920 px) те же 60 px — лишь 3%, мелким. Пропорция
 * экрана не учитывалась вовсе.
 *
 * Здесь — геометрическое ядро решения: единый коэффициент `scale = f(ширина арены)`
 * и базовые размеры объектов в **мировых единицах** (канон прежних констант при
 * `scale === 1`). Танк, ствол, снаряд, взрыв и якорь пузыря реплик бота считаются
 * в мировых единицах и рисуются через коэффициент; хит-зона танка масштабируется
 * тем же коэффициентом, что и тело, — попадание засчитывается ровно там, где видно
 * касание.
 *
 * ## Детерминизм реплеев
 *
 * Коэффициент — **чистая функция ЛОГИЧЕСКОЙ ширины арены** (`innerWidth` движка),
 * а не CSS-размера канваса на экране. В режиме воспроизведения логический размер
 * зафиксирован записью (`GamePlay.fixedLogicalSize`, поле `width` реплея), поэтому
 * `scale` при воспроизведении равен тому, что был при записи, — реплей
 * воспроизводится один в один на устройстве любого размера (канвас вписывается в
 * экран CSS-масштабированием, физику это не трогает). Ширина хранится в каждой
 * записи (`replay-codec`), значит `(seed + размер + ходы) → исход` остаётся чистой
 * функцией и после `encode → decode`.
 *
 * **Ограничение (осознанное):** живой бой с одним seed на экранах разной ширины
 * даёт разный `scale` → разные размеры объектов → потенциально разный исход. Это не
 * регресс: бой и раньше не был инвариантен к размеру экрана (рельеф считается от
 * высоты, точки старта — от ширины, #454). Инвариантность гарантируется не живому
 * бою, а РЕПЛЕЮ — тем, что запись пиннит логический размер и `scale` от него
 * производен. Записи, сделанные ДО #455, воспроизводились движком со `scale === 1`
 * независимо от ширины; после #455 их воспроизведение применяет `scale = f(ширина)`
 * и на ширине ≠ REFERENCE даст другой рельеф-независимый исход. Терпимо для учебного
 * проекта до релиза; терраформинг рельефа при этом не тронут (клиренс арены остаётся
 * фиксированным, см. `TANK_TOP_CLEARANCE`), поэтому сама карта у старых записей та же.
 */

/**
 * Опорная ширина арены, при которой `scale === 1` (объекты — в каноне прежних
 * констант). ≈ прежний дефолтный размер канваса движка (1000 px).
 */
export const WORLD_SCALE_REFERENCE_WIDTH = 1000;

/**
 * Нижняя граница коэффициента: на узких экранах (и при битой ширине) объекты не
 * вырождаются в точку. При min танк на 390 px — 30 px (7.7% ширины, ≤ 10%).
 */
export const WORLD_SCALE_MIN = 0.5;

/**
 * Верхняя граница коэффициента: на очень широких экранах объекты не раздуваются.
 * При max танк на 1920 px — 90 px (4.7% ширины, ≥ 4%).
 */
export const WORLD_SCALE_MAX = 1.5;

/**
 * Базовые размеры объектов мира в мировых единицах — канон прежних пиксельных
 * констант при `scale === 1`. Рендер и физика умножают их на текущий `scale`.
 */
export const WORLD_UNITS = {
    /** Ширина корпуса танка. */
    tankWidth: 60,
    /** Высота корпуса танка. */
    tankHeight: 30,
    /** Длина ствола. */
    gunpointWidth: 35,
    /** Толщина ствола. */
    gunpointHeight: 5,
    /** Смещение точки крепления ствола по X от левого края корпуса. */
    gunpointDeltaX: 30,
    /** Смещение точки крепления ствола по Y вверх от базовой линии танка. */
    gunpointDeltaY: 23,
    /** Радиус снаряда. */
    bulletRadius: 2,
    /** Максимальный радиус взрыва (он же радиус кратера в рельефе). */
    explosionMaxRadius: 50,
    /**
     * Базовая ширина облака (#572). Равна корпусу танка нарочно: `scale` облака тогда
     * читается прямо как «во столько корпусов оно» (см. `cloud-field.CLOUD_SCALE_*`),
     * а небо и арена живут по одному масштабу мира, а не по двум несвязанным клэмпам.
     */
    cloudWidth: 60,
} as const;

/**
 * Коэффициент масштаба мира от ширины арены (CSS/логические пиксели), зажатый в
 * `[WORLD_SCALE_MIN, WORLD_SCALE_MAX]`. Линеен в середине диапазона
 * (`width / REFERENCE`), на краях — насыщается клампом. Битая ширина (`NaN`,
 * `±Infinity`, ноль, отрицательная) → нижняя граница: объекты не вырождаются и не
 * раздуваются на мусорном входе (fail-safe, как `normalizeInset` в arena-insets).
 */
export function computeWorldScale(arenaWidth: number): number {
    if (!Number.isFinite(arenaWidth) || arenaWidth <= 0) return WORLD_SCALE_MIN;
    const raw = arenaWidth / WORLD_SCALE_REFERENCE_WIDTH;
    return Math.min(WORLD_SCALE_MAX, Math.max(WORLD_SCALE_MIN, raw));
}
