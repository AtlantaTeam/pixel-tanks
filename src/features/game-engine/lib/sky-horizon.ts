/**
 * Линия гор — общее число неба, а не собственность облаков (ревью #601).
 *
 * Полоса дальнего силуэта задаёт горизонт сразу трём модулям: облака не заезжают
 * за него (`cloud-field`), светило не проваливается под него (`sky-celestial`),
 * а рисует силуэт `sky-scene`. Пока константа жила в `cloud-field`, модуль облаков
 * работал складом чужих чисел, а высота полосы вообще была литералом `0.16` внутри
 * `paintMountains` — то есть докблоки трёх модулей ссылались на диапазон
 * `[0.46 … 0.62]`, который правка одного литерала молча делала неверным.
 *
 * Здесь обе величины рядом и производный от них верх полосы: правишь полосу —
 * едут все, кто на неё ссылается.
 */

/**
 * Доля высоты канваса, на которой стоит ПОДОШВА силуэта дальних гор, — то есть
 * линия горизонта, НИЗ горной полосы. `paintMountains` берёт
 * `bottom = height · MOUNTAIN_HORIZON_FRAC` и рисует полосу ВВЕРХ; ниже этой линии
 * силуэта нет вовсе, поэтому всё, что провалилось под неё, горы не перекрывают
 * (#583).
 */
export const MOUNTAIN_HORIZON_FRAC = 0.62;

/**
 * Высота полосы гор как доля высоты канваса. Арт 1024×130 (≈8:1) растягивается по
 * вертикали — читается как атмосферная дымка, гор в бою касаются взглядом мельком.
 */
export const MOUNTAIN_BAND_HEIGHT_FRAC = 0.16;

/** Верх горной полосы: выше него силуэта тоже нет — полоса, а не заливка до низа. */
export const MOUNTAIN_BAND_TOP_FRAC = MOUNTAIN_HORIZON_FRAC - MOUNTAIN_BAND_HEIGHT_FRAC;
