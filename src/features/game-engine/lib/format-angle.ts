/**
 * Угол ствола (радианы, конвенция движка — см. `Tank.gunpointAngle`) в градусы
 * для HUD: отрицательные радианы читаются напрямую (прицел вверх), положительные
 * — как дополнение до полного круга (прицел вниз). Перенесено из
 * `widgets/game-controls` без изменений — телеметрии верхнего оверлея
 * (`widgets/top-hud`) нужна та же формула, а дублировать её нельзя (единый
 * источник форматирования).
 *
 * Обе ветки — это один и тот же поворот на `-radians`, поэтому считаем его
 * прямо и сворачиваем в **полуинтервал [0, 360)**. Прежняя запись двумя ветками
 * давала на нуле `2π - 0 → 360°`: HUD в начале боя показывал «УГОЛ 360°» вместо
 * фактической горизонтали ствола (issue #457) — ноль и полный оборот в градусах
 * неразличимы, и правильный представитель класса ровно один, 0.
 *
 * Усечение (`| 0`, не `Math.floor`) сохранено намеренно: оно же переводит
 * нечисловой вход (NaN — сентинел в тестах движка) в 0, а не в подпись «NaN°».
 */
export const formatAngle = (radians: number): number => {
    const degrees = (-radians * 180) / Math.PI;

    return (((degrees % 360) + 360) % 360) | 0;
};
