import { createSeededRandom } from '@/shared/lib/random';
import { computeWorldScale, WORLD_UNITS } from './world-scale';
import { MAX_WIND } from './wind';

/**
 * Поле отдельных облаков — то, что показано в одобренном кадре
 * `docs/game-visuals/iteration-2/live-desktop.png`: крупные облака поштучно разбросаны
 * по небу, между ними пустое небо, у каждого своя высота и своя скорость.
 *
 * Прежняя реализация клала бесшовную ЛЕНТУ (`clouds-far/near.png`) и повторяла её по
 * горизонтали. Отсюда две жалобы приёмки (#514): небо получалось плотным, без
 * разреженности, а движение «передёргивало» — вся полоса ехала одним куском, и глазу
 * не за что зацепиться, кроме шва повтора. Спрайты `cloud-1..3.png` при этом лежали
 * в `public/art/` неиспользованными.
 *
 * ## Модель плоского облачного слоя (#572)
 *
 * Облако — объект мира, поэтому его базовая ширина берётся из `WORLD_UNITS` и общего
 * `computeWorldScale` (как у танка), а НЕ из собственной доли ширины экрана. Раньше две
 * несвязанные формулы (`computeWorldScale` для танка и `ширина·0.15` для облака) давали
 * на 1920 облако в три корпуса танка: обе упирались в свой потолок на разной ширине,
 * и пропорция «облако к танку» гуляла с шириной экрана. Теперь пропорция задаётся один
 * раз числом (`WORLD_UNITS.cloudWidth`), а небо и арена живут по одному закону.
 *
 * План облака (дальний/ближний) выведен из его ВЫСОТЫ, а не брошен отдельным random.
 * Облака лежат на одной высоте над землёй, смотрим почти горизонтально — значит для
 * облака на удалении `d` видимый размер, скорость и возвышение над горизонтом все ∝ 1/d,
 * то есть все пропорциональны расстоянию от линии горизонта. Отсюда единственный
 * параметр `t = cloudPlane(yFrac)` (0 — у линии гор, 1 — у верха кадра), из которого
 * выводятся размер, скорость, прозрачность (дымка) и вертикальное сжатие. Сжатие делает
 * далёкие облака плоскими полосками (слой под острым углом), а не теми же клубами
 * помельче — одного уменьшения размера для «естественности» не хватает.
 */

export type TCloudSpriteKey = 'cloud1' | 'cloud2' | 'cloud3';

const SPRITE_KEYS: readonly TCloudSpriteKey[] = ['cloud1', 'cloud2', 'cloud3'];

/** Облако поля: какой спрайт, где стоит, с какой скоростью и в каком плане плывёт. */
export type TCloudInstance = {
    sprite: TCloudSpriteKey;
    /** Стартовая позиция как доля ширины поля, [0, 1). */
    xFrac: number;
    /** Верх облака как доля высоты канваса, [Y_MIN, Y_MAX]. */
    yFrac: number;
    /** Скорость параллакса, px/мс. Выведена из плана: у горизонта медленнее. */
    speed: number;
    /** Множитель размера спрайта относительно базового (`cloudSpriteWidth`), [CLOUD_SCALE_MIN, CLOUD_SCALE_MAX]. */
    scale: number;
    /** Множитель прозрачности от плана: у горизонта бледнее (дымка), [CLOUD_HAZE_MIN, 1]. */
    alpha: number;
    /** Вертикальное сжатие спрайта от плана: у горизонта площе, [CLOUD_SQUASH_MIN, 1]. */
    squashY: number;
    /** Зеркалить спрайт по X при отрисовке — те же три спрайта дают шесть силуэтов. */
    mirror: boolean;
};

/**
 * Одно облако примерно на столько CSS-пикселей ширины. Замер одобренного кадра:
 * четыре облака на 1280 CSS — то есть шаг около 320. Отсюда и разреженность: плотность
 * задаётся шагом, а не тем, сколько облаков поместилось в ленту.
 */
export const CLOUD_DENSITY_STEP_PX = 320;

/** Границы числа облаков: на узком экране их не должно остаться ноль, на широком —
 *  не больше десятка (потолок держит и читаемость неба, и бюджет кадра). */
export const CLOUD_COUNT_MIN = 3;
export const CLOUD_COUNT_MAX = 10;

/**
 * Доля высоты канваса, на которой начинается силуэт дальних гор (`sky-scene`).
 * Единый источник правды: тут его берёт модель плана облака (`cloudPlane` — линия
 * горизонта = 0), а `sky-scene.paintMountains` и клэмп низа облака рисуют по нему же,
 * чтобы облако не заезжало за силуэт (#572).
 */
export const MOUNTAIN_HORIZON_FRAC = 0.62;

/**
 * Вертикальный разброс: облака живут в верхней части неба, над рельефом. Расширен с
 * прежних 0.04–0.34 (#514) — в одобренном эталоне облака стоят и заметно ниже, вплотную
 * к силуэту гор, а не только у самого верха кадра. Диапазон #514 не виноват в жалобе
 * на «крупное у горизонта» (#572) — виновата была развязка высоты и плана, поэтому
 * сужать его в лечение не нужно.
 */
export const Y_MIN = 0.04;
export const Y_MAX = 0.48;

/**
 * Границы масштаба облака по плану. `cloudWidth` в `WORLD_UNITS` равен корпусу танка,
 * поэтому `scale` читается прямо как «во столько корпусов танка облако»: у горизонта
 * (t→0) — около половины корпуса, у верха кадра (t→1) — до `CLOUD_SCALE_MAX` корпусов.
 * Потолок держит самое крупное облако не более ~2 корпусов на любой ширине (#572) —
 * прежние «до трёх корпусов» и читались тяжело.
 */
export const CLOUD_SCALE_MIN = 0.5;
export const CLOUD_SCALE_MAX = 1.8;

/**
 * Разброс масштаба ВНУТРИ плана (± к выведенному из высоты значению). Без него поле
 * распалось бы в гладкую функцию высоты — ровно те «три чётких пресета размера»,
 * которых избегали в #515. С ним облака на близких высотах всё равно чуть разного
 * размера.
 */
export const CLOUD_SCALE_JITTER = 0.12;

/**
 * Скорости параллакса по плану, px/мс. Диапазон — прежние крайние `CLOUD_SPEEDS`
 * (#514): у горизонта (t→0) облако ползёт медленно, у верха кадра (t→1) — быстрее.
 * Разные высоты дают разные скорости — это и есть параллакс (раньше скорость была
 * одна на всю ленту, потому движение читалось рывком целого слоя).
 */
export const CLOUD_SPEED_MIN = 0.004;
export const CLOUD_SPEED_MAX = 0.016;

/**
 * Нижняя граница прозрачности у горизонта: далёкое облако бледнее (воздушная дымка).
 * У верха кадра множитель = 1 (полная прозрачность пресета). Раньше альфа была одна
 * на весь слой — дымки не было вовсе (#572).
 */
export const CLOUD_HAZE_MIN = 0.5;

/**
 * Нижняя граница вертикального сжатия у горизонта: слой, видимый под острым углом,
 * сжат по вертикали, поэтому далёкие облака читаются плоскими полосками. У верха
 * кадра множитель = 1 (спрайт в своих пропорциях).
 */
export const CLOUD_SQUASH_MIN = 0.45;

/**
 * Дрейф при штиле: при нулевом ветре облака не встают колом, а еле ползут. Ноль
 * выглядел бы поломкой («небо замерло»), а не безветрием.
 */
const CALM_DRIFT = 0.25;

/** Прибавка к дрейфу при ветре в полную силу (`MAX_WIND`). */
const WIND_GAIN = 1.75;

/** Линейная интерполяция: `a` при t=0, `b` при t=1. */
function lerp(a: number, b: number, t: number): number {
    return a + (b - a) * t;
}

/** Зажимает `value` в отрезок `[min, max]`. */
function clamp(value: number, min: number, max: number): number {
    return Math.min(max, Math.max(min, value));
}

/**
 * Множитель скорости облаков от ветра боя. Знак — направление: ветер влево несёт
 * облака влево, и небо перестаёт спорить с траекторией снаряда (#518).
 *
 * Нормируется на `MAX_WIND` — тот же потолок, по которому HUD рисует пипы силы.
 * Своя шкала здесь означала бы, что «три пипа» в интерфейсе и «сильный ветер» на небе
 * разъезжаются.
 *
 * Ветер в бою ПОСТОЯНЕН и выведен из сида, поэтому небо дует одинаково весь бой,
 * а от боя к бою по-разному. Менять его в полёте нельзя: он входит в физику снаряда
 * и в реплеи.
 */
export function windFactor(wind: number): number {
    if (!Number.isFinite(wind)) return CALM_DRIFT;
    const strength = Math.min(1, Math.abs(wind) / MAX_WIND);
    const magnitude = CALM_DRIFT + strength * WIND_GAIN;
    return wind < 0 ? -magnitude : magnitude;
}

/**
 * План облака из его высоты: `0` — у линии гор (дальний), `1` — у верха кадра
 * (ближний). Все видимые величины плоского слоя (размер, скорость, дымка, сжатие)
 * пропорциональны расстоянию от линии горизонта, поэтому параметр один и берётся из
 * `yFrac`, а не бросается отдельным random (#572). Зажат в [0, 1] — облако вне
 * штатного диапазона высот не даёт отрицательного/сверхъединичного плана.
 */
export function cloudPlane(yFrac: number): number {
    const span = MOUNTAIN_HORIZON_FRAC - Y_MIN;
    if (span <= 0) return 1;
    return clamp((MOUNTAIN_HORIZON_FRAC - yFrac) / span, 0, 1);
}

/**
 * Базовая ширина облачного спрайта в CSS-пикселях: мировая единица `cloudWidth`,
 * помноженная на общий масштаб мира (#572). Та же геометрия, что у танка
 * (`computeWorldScale`), поэтому пропорция «облако к танку» одна на всех ширинах, а не
 * вытекает из двух несвязанных клэмпов. Битую ширину `computeWorldScale` уводит в
 * нижнюю границу — размер не вырождается в ноль.
 */
export function cloudSpriteWidth(canvasWidth: number): number {
    return WORLD_UNITS.cloudWidth * computeWorldScale(canvasWidth);
}

export function cloudCount(width: number): number {
    if (!Number.isFinite(width) || width <= 0) return CLOUD_COUNT_MIN;
    const raw = Math.round(width / CLOUD_DENSITY_STEP_PX);
    return Math.min(CLOUD_COUNT_MAX, Math.max(CLOUD_COUNT_MIN, raw));
}

/**
 * Раскладывает облака по небу детерминированно от сида: один сид — то же небо
 * (критерий #479). Поток RNG отделён суффиксом `::clouds`, чтобы не сдвинуть
 * последовательность боя (рельеф, ветер, бот) — иначе разошёлся бы реплей.
 *
 * Позиции по X раскладываются по СЕКТОРАМ (`i + jitter`), а не свободным random: при
 * свободном два облака регулярно слипались в кучу, оставляя полнеба пустым, — а нужна
 * ровная разреженность, как в одобренном кадре.
 *
 * Высота (`yFrac`) смещена к линии гор (`Math.sqrt` от равномерного): у горизонта
 * облаков больше и стоят они теснее — перспектива сжимает расстояния (#572). Размер,
 * скорость, прозрачность и сжатие каждого облака ВЫВОДЯТСЯ из его высоты через
 * `cloudPlane`, а не бросаются отдельными random — план и высота не могут разъехаться.
 *
 * Порядок и число вызовов `random()` изменены осознанно относительно #515 (пять на
 * облако вместо шести): отдельный бросок яруса глубины убран — план теперь выводится
 * из высоты. Детерминизм «один сид → то же небо» это не трогает (тест зелёный).
 */
export function buildCloudField(seed: number | string, width: number): TCloudInstance[] {
    const random = createSeededRandom(`${seed}::clouds`);
    const count = cloudCount(width);
    const field: TCloudInstance[] = [];
    for (let i = 0; i < count; i++) {
        const jitter = 0.15 + random() * 0.7;
        const sprite = SPRITE_KEYS[Math.floor(random() * SPRITE_KEYS.length) % SPRITE_KEYS.length];
        // Смещение к горизонту: sqrt(u) тянет выборку к 1, то есть к Y_MAX (линии гор).
        const yFrac = Y_MIN + Math.sqrt(random()) * (Y_MAX - Y_MIN);
        const t = cloudPlane(yFrac);
        const scaleJitter = (random() - 0.5) * 2 * CLOUD_SCALE_JITTER;
        const scale = clamp(
            lerp(CLOUD_SCALE_MIN, CLOUD_SCALE_MAX, t) + scaleJitter,
            CLOUD_SCALE_MIN,
            CLOUD_SCALE_MAX,
        );
        field.push({
            sprite,
            xFrac: (i + jitter) / count,
            yFrac,
            speed: lerp(CLOUD_SPEED_MIN, CLOUD_SPEED_MAX, t),
            scale,
            alpha: lerp(CLOUD_HAZE_MIN, 1, t),
            squashY: lerp(CLOUD_SQUASH_MIN, 1, t),
            mirror: random() < 0.5,
        });
    }
    return field;
}
