/**
 * Контракт safe-зоны арены (фаза 3, issue #453).
 *
 * Арена — канвас `inset:0` во весь экран; верхний HUD и нижняя палуба рисуются
 * поверх неё оверлеями. Движок про их высоты сам не знает и по умолчанию считает
 * ландшафт по полной высоте канваса — из-за чего низ поля прячется под палубой.
 *
 * Этот модуль — геометрическое ядро контракта: чистые функции, считающие
 * свободную (не закрытую оверлеями) зону арены из высоты канваса и инсетов.
 * Отрисовка их пока не использует (карточка вводит только контракт и тесты);
 * рельеф и танки перейдут в зону следующими карточками фазы (#454–#456).
 *
 * **Единственный источник правды по инсетам — поле `arenaInsets` стора боя**
 * (`game.store.ts`): оба оверлея (React) публикуют туда свою фактическую высоту
 * через `ResizeObserver` (хук `useArenaInset`), движок читает их через
 * `GameCanvas` и хранит производную зону. CSS-переменные `--arena-inset-*`
 * сознательно НЕ заводим: это была бы вторая копия высот (строково-типизированная,
 * требующая `getComputedStyle`-парсинга на стороне движка) — критерий «источник
 * правды один» требует ровно одного места, а стор уже опосредует связь React ↔
 * движок (угол/сила/ветер/размер поля живут там же).
 */

/** Высоты оверлеев, закрывающих арену сверху и снизу (CSS-пиксели). */
export type TArenaInsets = {
    /** Фактическая высота верхнего оверлея (HUD). */
    top: number;
    /** Фактическая высота нижнего оверлея (палубы). */
    bottom: number;
};

/** Свободная (не закрытая оверлеями) вертикальная зона арены (CSS-пиксели). */
export type TArenaZone = {
    /** Смещение верха зоны от верха канваса. */
    top: number;
    /** Высота зоны. По построению никогда не отрицательна (см. `computeArenaZone`). */
    height: number;
};

/** Инсеты по умолчанию — оверлеев нет, зона равна всему канвасу. */
export const EMPTY_ARENA_INSETS: TArenaInsets = { top: 0, bottom: 0 };

/**
 * Приводит одиночный инсет к неотрицательному конечному числу: `NaN`,
 * `±Infinity` и отрицательные значения → 0. `ResizeObserver` штатно отдаёт
 * конечную неотрицательную высоту, но контракт обязан выдерживать и мусор на
 * входе (аномально большие/битые значения) — иначе зона ушла бы в `NaN`/минус.
 */
export function normalizeInset(value: number): number {
    if (!Number.isFinite(value) || value < 0) return 0;
    return value;
}

/**
 * Считает свободную зону арены из высоты канваса и инсетов оверлеев.
 *
 * Зажатие гарантирует, что зона не уходит в отрицательную высоту при любых
 * инсетах: верхний инсет не больше высоты канваса, нижний — не больше того, что
 * осталось под верхним. Сумма аномально больших инсетов (перекрытие оверлеев в
 * коротком landscape) даёт зону нулевой высоты, а не отрицательной.
 */
export function computeArenaZone(canvasHeight: number, insets: TArenaInsets): TArenaZone {
    const height = Math.max(0, Number.isFinite(canvasHeight) ? canvasHeight : 0);
    const top = Math.min(normalizeInset(insets.top), height);
    const bottom = Math.min(normalizeInset(insets.bottom), height - top);
    return { top, height: height - top - bottom };
}

/**
 * Клиренс сверху свободной зоны под корпус танка и ствол (CSS-пиксели). Танк
 * рисуется от `y - tankHeight` вверх, ствол торчит ещё выше; резерв держит пик
 * рельефа достаточно низко, чтобы танк на нём не уходил под верхний оверлей (HUD).
 * Значение — высота корпуса (30) + вылет ствола (≈35) с небольшим запасом; это
 * канон констант `Tank` (60×30, ствол 35×5). Масштаб мира (#455) сделает клиренс
 * производным от единого коэффициента, пока — фиксированная величина.
 */
export const TANK_TOP_CLEARANCE = 72;

/**
 * Границы высоты рельефа над нижним краем канваса (CSS-пиксели). Поверхность земли
 * в столбце `x` лежит на `canvasHeight - heights[x]`, поэтому обе границы = высота
 * поверхности над низом канваса: `min` — низины, `max` — пики.
 */
export type TTerrainHeights = {
    /** Минимальная высота поверхности над низом канваса (самые низины рельефа). */
    min: number;
    /** Максимальная высота поверхности над низом канваса (пики рельефа). */
    max: number;
};

/**
 * Считает границы высоты рельефа так, чтобы вся поверхность легла в свободную зону
 * арены (safe-зона, issue #454):
 *
 * - **низ рельефа поднят на нижний инсет** — низина не уходит под палубу
 *   (`min`/`max` смещены на `bottom` инсет, поэтому даже самая глубокая низина
 *   поверхности `canvasHeight - min` лежит на базовой линии `canvasHeight - bottom`
 *   или выше);
 * - **амплитуда считается от высоты ЗОНЫ, а не канваса** — рельеф не растягивается
 *   на весь экран;
 * - **пик ограничен клиренсом** `TANK_TOP_CLEARANCE` — танк со стволом на пике не
 *   уходит под верхний оверлей (HUD).
 *
 * Пустые инсеты → зона равна канвасу, нижний инсет 0, клиренс не связывает: границы
 * вырождаются ровно в прежние `floor(H/2)` и `floor(H/2)/4` — поведение движка до
 * safe-зоны сохраняется бит-в-бит (то, на что опираются реплеи, записанные раньше).
 */
export function computeTerrainHeights(canvasHeight: number, insets: TArenaInsets): TTerrainHeights {
    // Инсеты округляются до пикселя: рельеф — целочисленный (Ground.heights),
    // а реплей хранит инсеты как u16 (см. replay-codec). Округление здесь делает
    // генерацию живого боя и воспроизведение записи бит-в-бит совпадающими (обе
    // стороны берут `Math.round` от одного источника) и заодно гасит суб-пиксельный
    // дребезг `ResizeObserver` — рельеф не перекладывается на изменение 0.1px.
    const rounded: TArenaInsets = {
        top: Math.round(normalizeInset(insets.top)),
        bottom: Math.round(normalizeInset(insets.bottom)),
    };
    const zone = computeArenaZone(canvasHeight, rounded);
    const height = Math.max(0, Number.isFinite(canvasHeight) ? canvasHeight : 0);
    // Нижний инсет после зажатия зоны: то, что осталось под свободной зоной.
    const bottom = height - (zone.top + zone.height);
    const field = zone.height;
    // База амплитуды повторяет прежнюю формулу рельефа (Ground): пик — половина
    // поля, низина — четверть пика. От высоты ЗОНЫ, а не канваса.
    const baseMax = Math.floor(field / 2);
    const min = baseMax / 4;
    // Пик не должен поднимать танк со стволом под HUD: зажимаем амплитуду сверху
    // клиренсом. На нормальной зоне (baseMax ≪ field) клиренс не связывает —
    // амплитуда остаётся прежней. `Math.max(min, …)` страхует крошечную зону, где
    // клиренс уже опустил бы пик ниже низины (тогда рельеф вырождается в ровный).
    const cappedMax = Math.max(min, Math.min(baseMax, Math.max(0, field - TANK_TOP_CLEARANCE)));
    return { min: bottom + min, max: bottom + cappedMax };
}
