/**
 * Ход игрока в записи боя. Бот полностью детерминирован seed'ом,
 * поэтому его действия в реплей не записываются — только действия игрока.
 */
export type TReplayMove =
    /** Перемещение танка по горизонтали (пиксели, знак — направление). */
    | { kind: 'move'; delta: number }
    /**
     * Выстрел. Угол — точный float64: физика чувствительна к младшим битам,
     * квантование сломало бы идентичность воспроизведения. Сила — целое 1–20.
     *
     * `weaponId` — ординал типа оружия (`WEAPON_KIND_ORDER`, 0..3), issue #483.
     * Опционален: отсутствует → фугас (тип 0). Записи, сделанные ДО variety оружия,
     * `weaponId` не имеют и воспроизводятся ровно как играли — фугасом. Тип нужен в
     * записи, потому что кратер (форма/глубина по типу) меняет рельеф, а рельеф —
     * траектории и прицел бота: без типа реплей разошёлся бы с оригиналом.
     */
    | { kind: 'fire'; angle: number; power: number; weaponId?: number };

/**
 * Инсеты safe-зоны арены на момент боя (CSS-пиксели): высоты верхнего (HUD) и
 * нижнего (палуба) оверлеев. Рельеф генерится ВНУТРИ свободной зоны между ними
 * (issue #454), поэтому воспроизведение обязано знать те же инсеты — иначе рельеф
 * и счёт разойдутся. Записи до safe-зоны инсетов не имеют (`undefined`): движок
 * трактует их как нулевые и воспроизводит рельеф во весь канвас, как и был записан.
 */
export type TReplayInsets = {
    top: number;
    bottom: number;
};

/**
 * Полная запись боя: seed + логический размер поля + инсеты safe-зоны + ходы игрока.
 * Тип seed значим: `createSeededRandom` использует число напрямую,
 * а строку хеширует — `123` и `'123'` дают разные последовательности.
 *
 * `width`/`height` — логический (CSS) размер поля в пикселях на момент боя.
 * Вся физика идёт в абсолютных пикселях (рельеф `Ground.generate` тратит по
 * одному `random()` на пиксель ширины, танки стоят в `W/4` и `3W/4`, скорость
 * снаряда завязана на размер), поэтому воспроизведение обязано идти на том же
 * размере — иначе рельеф, ветер и траектории разойдутся, а счёт не совпадёт.
 * Реплей проигрывается на canvas этого фиксированного размера, вписанном в
 * экран CSS-масштабированием.
 *
 * `insets` — опционально: safe-зона арены (#454). Отсутствует у записей до
 * safe-зоны; движок читает их как нулевые (рельеф во весь канвас).
 *
 * ## Известное расхождение: заморозка снаряда после детонации (#582, PR #601)
 *
 * До этой правки `Bullet.move()` работал и ПОСЛЕ детонации: усечение `(x + dx) | 0`
 * уносило снаряд на пиксель за кадр, и воронка резалась там, куда он успел уползти за
 * время взрыва (замер: 156 px при ветре −0.02). Теперь снаряд стоит, и воронка ложится
 * в точку попадания — то есть другой рельеф, другие траектории следующих выстрелов,
 * другой прицел бота, возможно другой счёт у записей с ненулевым ветром.
 *
 * **Версия формата под это НЕ поднята — расхождение принято осознанно.** Прецедент
 * обратный (`weather` → v5) есть, но чтобы играть старые записи «как записаны», в
 * кадровом цикле пришлось бы держать живыми ОБА старых поведения сразу: и дрейф в
 * `move()`, и прежний гейт `isHit` (число кадров взрыва зависело от того, когда снаряд
 * дотонет под поверхность). Это буг-совместимость в горячем цикле ради записей,
 * которых у нас нет способа посчитать. Решение «версионировать или принять» вынесено
 * человеку отдельной карточкой; пока — принято, и написано здесь, а не подразумевается.
 */
export type TReplay = {
    seed: number | string;
    width: number;
    height: number;
    insets?: TReplayInsets;
    moves: TReplayMove[];
    /**
     * Бой записан в эпоху погоды (#546/#547) — воспроизводить с модификаторами ветра.
     * Ставится ДЕКОДЕРОМ по версии формата (v5), в кодировании не участвует: у живого боя
     * погода есть всегда, а запись прошлой эпохи обязана играться так, как записана —
     * иначе снег и буря меняют траектории задним числом примерно у четверти записей.
     * `undefined` (записи v2–v4 и ручные фикстуры) читается как «без погоды».
     */
    weather?: boolean;
};
