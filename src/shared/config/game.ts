/**
 * Геймдизайн-константы боя — общий источник для всех слоёв. Живут в `shared`
 * (как `POWER_MIN/POWER_MAX`), чтобы их читали из одной точки и `features/game-engine`
 * (стор HP, статистика боя), и `payload/collections/scores` + `features/daily-challenge`
 * (потолок очков лидерборда). FSD запрещает завязку `payload`/`entities` на `features`,
 * поэтому общий источник обязан лежать в `shared`, а не в модуле стора.
 */

/** Максимум HP танка (GDD §2.5). HP боя живёт в диапазоне 0..MAX_HP. */
export const MAX_HP = 100;

/** Бюджет манёвров на матч (GDD §2.3) — стартовое `moves` и знаменатель показа «X / N». */
export const MOVE_BUDGET = 4;

/**
 * Жёсткий потолок очков лидерборда за бой. Очки — производная метрика
 * (урон ≤ MAX_HP + остаток HP ≤ MAX_HP + точность ≤ 100 %), см.
 * `computeLeaderboardPoints`. Максимум формулы — `3 · MAX_HP` (100 % точности
 * совпадает по величине с MAX_HP), поэтому это и есть серверная граница
 * валидации записи `scores`/`submitDailyScore`. До Auth сервер не пересчитывает
 * очки клиента — узкий потолок формулы (а не запас «на всякий случай») режет
 * окно накрутки daily-лидерборда анонимным POST'ом.
 */
export const MAX_LEADERBOARD_POINTS = 3 * MAX_HP;
