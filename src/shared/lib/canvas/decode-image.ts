/**
 * Ждёт, пока пиксели картинки реально готовы к отрисовке на канвасе.
 *
 * Событие `load` в Chromium означает «байты пришли», а не «кадр декодирован»:
 * декодирование PNG/JPEG асинхронно, и `drawImage` сразу после `load` может
 * нарисовать ПУСТО, не бросив ошибки. Пока результат такого `drawImage` рисуется
 * каждый кадр — промах самолечится на следующем. Но у нас он КЕШИРУЕТСЯ в
 * offscreen (тонированный силуэт гор `ensureTintedMountain`, кайма
 * `ensureEdgeMountain`), и пустой кадр залипает на весь бой: горы не появляются
 * больше никогда, даже после ресайза со сбросом статического слоя.
 *
 * Замер на прод-сборке (`/game?seed=vrt-day-2`, 1280×800, шесть заходов):
 * силуэт дальних гор пропадал в 2 из 6 загрузок и не возвращался после
 * принудительной перестройки статического слоя. Ровно этот класс дефектов и
 * делает эталонные кадры сцены недостижимыми — поэтому картинка публикуется
 * потребителям только после `decode()`.
 *
 * Отказ `decode()` (битый файл, 404) резолвится тем же элементом, а не reject:
 * потребители и так гардят отрисовку по `image.width`, а зависший промис повесил
 * бы загрузку сцены целиком. `decode` отсутствует в happy-dom — тогда ждать
 * нечего, отдаём картинку как есть.
 */
export function whenDecoded(image: HTMLImageElement): Promise<HTMLImageElement> {
    if (typeof image.decode !== 'function') return Promise.resolve(image);
    return image.decode().then(
        () => image,
        () => image,
    );
}
