// Интерфейсы адаптеров ralph — контракты точек расширения фреймворка (#262, фаза 5).
//
// Зачем. Ядро петли (issue → код → PR → ревью → гейт → мердж) переносимо между
// проектами; проектно-специфичное ПОВЕДЕНИЕ (иной форж, иной стек сборки, иной
// механизм деплоя, иной нотификатор, иной агент-рантайм) — нет. #204 сняло
// проектные ЗНАЧЕНИЯ в `ralph.config.json`; этот файл описывает ИНТЕРФЕЙСЫ для
// того, что значением-в-конфиге не закрыть. Пять швов — ровно из плана фазы
// (`docs/ralph-mini-framework/plan.md`, фаза 5) и кандидатов PRD (§«Кандидаты в
// адаптеры»): источник задач (форж), гейт, нотификатор, деплой-проверка, рантайм
// кодер-сессии.
//
// Что это и что НЕ это. Здесь — ТОЛЬКО контракты (типы и сигнатуры), которым в
// фазе 5 подчинят текущие реализации (#369) и против которых напишут контрактный
// сьют (#370). Реализаций тут нет.
//
// Инварианты в контракте. Тип не выражает «бросает» vs «глотает», поэтому режим
// отказа каждого метода зафиксирован в докстроке — это часть контракта, не деталь:
//   • Fail-closed (метод БРОСАЕТ при сбое) — всё, что решает, что́ брать в работу и
//     что мерджить: чтение очереди issues, резолв sha мерджа, прогон чеков. Тихий
//     дефолт здесь — худший исход (инвариант №1 в `.claude/ralph/CLAUDE.md`).
//   • Fail-open (метод НЕ бросает, сигналит возвратом/логом) — косметика, чей сбой
//     не должен ронять петлю: доставка пуша, метки, закрытие milestone, синк доски.
//
// Форма. Erasable-only TypeScript без билд-шага (нативный type stripping Node ≥24):
// только `type`-алиасы и аннотации — ни `enum`, ни namespace-рантайма, ни parameter
// properties; в рантайме от файла не остаётся ничего. Стиль ядра — `type` без
// префикса `T` (как `Issue`/`Phase`/`GateEnv`/`DeployOutcome` в соседних модулях),
// не app-конвенция `TName`. Модуль САМОДОСТАТОЧЕН: не импортирует боевые модули
// ядра — контракт есть абстракция, которой они подчиняются, а не наоборот (иначе
// зависимость поехала бы «абстракция → реализация»). Формы совпадают с боевыми
// структурно; #369 сведёт их в один источник.

// ---------------------------------------------------------------------------------
// Общие типы данных швов
// ---------------------------------------------------------------------------------

// Issue в форме, которую читает петля (`gh issue list --json number,title,labels,author`).
// Тело issue петля НЕ запрашивает — его читает кодер-сессия по номеру; поэтому здесь
// нет `body`.
export type Issue = {
    number: number;
    title: string;
    labels?: Array<{ name: string }>;
    author?: { login?: string };
};

// PR в форме, которую читает петля (`gh pr list --json number,labels`). `labels`
// нужны гейту для проверки `hold`/`blocked`.
export type PullRequest = {
    number: number;
    labels?: Array<{ name: string }>;
};

// Фаза = milestone (очередь задач) + ветка (`feature/…`). State адресует фазу по
// ИМЕНИ milestone, не по индексу (инвариант M7).
export type Phase = { milestone: string; branch: string };

// ---------------------------------------------------------------------------------
// 1. Источник задач (форж): issues, PR, мердж, метки, milestone, доска
// ---------------------------------------------------------------------------------
//
// Абстракция над форжем (сейчас — GitHub через `gh`; кандидаты — GitLab/Gitea).
// Создание PR в контракт НЕ входит: ralph делегирует его кодер-сессии рантайма
// (`claude -p`-сессия «создай PR»), а не коду ядра — ядро лишь НАХОДИТ готовый PR
// (`findOpenPullRequest`) и определяет факт мерджа. Управление меткой `hold` тоже
// не в контракте: снять её может только человек (структурный барьер #222) — в
// адаптере намеренно нет такого метода.

export type TaskSourceAdapter = {
    // Открытые issues фазы, ГОТОВЫЕ к работе: без метки `blocked`, автор в
    // allowlist (защита от инъекций через чужие issues, C3), отсортированы по
    // номеру возрастанию (петля берёт первый). Fail-closed: бросает при сбое форжа.
    listReadyIssues(milestone: string): Issue[];

    // ВСЕ открытые issues фазы без фильтров — проверка готовности фазы к сдаче
    // (C2: «очередь пуста» ≠ «фаза готова»; blocked и чужие issues тоже держат
    // фазу открытой). Fail-closed.
    listAllOpenIssues(milestone: string): Issue[];

    // Открытый PR ветки фазы в `main` или null. Fail-closed на неоднозначности:
    // при >1 открытом PR на ветку возвращает null (не гадать, что мерджить).
    findOpenPullRequest(branch: string): PullRequest | null;

    // Смерджен ли squash-PR ветки фазы в `main`.
    isPhaseMerged(phase: Pick<Phase, 'branch'>): boolean;

    // Номер смердженного PR ветки фазы или null.
    mergedPullRequestNumber(phase: Pick<Phase, 'branch'>): number | null;

    // Squash-мердж PR. `headSha` (если задан и валиден) прижимает мердж к точному
    // sha головы, верифицированному гейтом — закрывает TOCTOU-окно между чеками и
    // мерджем (`--match-head-commit`). Вызывается ядром только после зелёного гейта.
    mergePullRequest(prNumber: number, headSha?: string | null): void;

    // Метка `blocked` на PR ветки фазы. Ставит/снимает ТОЛЬКО раннер (не кодер- и
    // не чини-сессия — #217); fail-open: сбой форжа не роняет петлю.
    addBlockedLabel(branch: string): void;
    removeBlockedLabel(branch: string): void;

    // Косметика после сдачи фазы, fail-open (сбой логируется, петля идёт дальше):
    // закрыть milestone фазы и синхронизировать доску проекта.
    closeMilestone(title: string): void;
    syncBoard(): void;
};

// ---------------------------------------------------------------------------------
// 2. Гейт: композиция и детерминированный прогон чеков
// ---------------------------------------------------------------------------------
//
// Шов «как гонять чеки» (npm vs cargo/make/gradle). Только ПРОГОН и его вердикт —
// сам мердж и метки принадлежат форжу (`TaskSourceAdapter`); их композицию в цикл
// сдачи делает оркестратор. Контракт хранит деление база/prod и требование
// fail-fast-порядка (дёшево→дорого: security→coverage→e2e) — порядок задаёт автор
// конфига, адаптер его не переставляет.

// Пара [имя, команда] одного чека (`['typecheck', 'npm run typecheck']`).
export type GateCheck = [name: string, command: string];

// Первый красный чек: имя, команда, выжимка вывода — для лога и пуша человеку.
export type RedCheck = { name: string; cmd: string; excerpt: string };

// Вердикт прогона чеков на детач-чекауте точного sha головы PR. Объект (а не голый
// boolean): зелёному нужен `verifiedHead` для `--match-head-commit`, красному —
// `redCheck` для отчёта. Взаимоисключающи: green ⇒ verifiedHead!=null & redCheck=null;
// !green ⇒ verifiedHead=null & redCheck!=null.
export type GateCheckResult = {
    green: boolean;
    verifiedHead: string | null;
    redCheck: RedCheck | null;
};

export type GateAdapter = {
    // Состав чеков для профиля. Прод дропает дедуп-чеки (test↔coverage) и добавляет
    // толстые (security→coverage→e2e), сохраняя fail-fast-порядок; иначе — база.
    resolveChecks(profileName?: string): GateCheck[];

    // Прогнать чеки на детач-чекауте ТОЧНОГО sha головы PR. Детерминированно, агенту
    // на слово не верит. Fail-closed: битый sha/чекаут → бросает (не «считать
    // зелёным»). Зелёный результат несёт верифицированный sha для мерджа.
    runChecks(branch: string, prNumber: number): GateCheckResult;
};

// ---------------------------------------------------------------------------------
// 3. Нотификатор: доставка пуш-событий человеку
// ---------------------------------------------------------------------------------
//
// Шов доставки (сейчас Telegram; кандидаты — Slack/email). Эталон уже изолирован
// (`telegram-notifier.js`): самостоятельный модуль, DI, свой журнал побочек.

// Контекст доставки, который ядро прокидывает нотификатору насквозь (не часть payload,
// а точки DI): `logFn` — куда писать лог доставки (у эталона — общий `ralph.log`, иначе
// доставка логировалась бы мимо), `execFn` — подменяемый исполнитель (тестовая инъекция
// вместо реальной сети). Оба опциональны: реализация, которой они не нужны, их игнорирует,
// но узаконены в сигнатуре, чтобы реализация фазы 6 (Slack/email) их не потеряла.
export type NotifierDeliveryOpts = {
    logFn?: (msg: string) => void;
    execFn?: (file: string, args: string[], opts?: Record<string, unknown>) => string;
};

export type NotifierAdapter = {
    // Доставить текст события человеку. Fail-open по определению (alert-first): при
    // неудаче доставки ВОЗВРАЩАЕТ false и НИКОГДА не бросает — сбой канала оповещения
    // не должен ронять или блокировать петлю. Пуш-событие — просто текст (без
    // структурированного payload и разметки); `opts` — не данные, а прокинутый ядром
    // контекст доставки (лог/исполнитель), см. NotifierDeliveryOpts.
    notify(text: string, opts?: NotifierDeliveryOpts): boolean;
};

// ---------------------------------------------------------------------------------
// 4. Деплой-проверка: пост-мердж верификация релиза
// ---------------------------------------------------------------------------------
//
// Шов «зелёный ли релиз после мерджа» (сейчас GitHub Actions workflow + HTTP
// health-URL прода; у другого проекта — иной механизм). Классификация fail-closed:
// GREEN только при зелёном воркфлоу И живом проде — иначе барьер стопорит трек.

// Статус ожидания деплой-воркфлоу для sha мерджа.
export type DeployStatus = 'completed' | 'timeout' | 'not-found';

// Исход деплой-воркфлоу для конкретного sha.
export type DeployOutcome = {
    status: DeployStatus;
    conclusion: string | null;
    sha: string;
    url: string | null;
    runId: number | null;
};

// Итог health-чека прода. `reason: 'config'` — health-URL не задан/кривой (даёт
// КРАСНЫЙ деплой, отличимый от «прод не отвечает», а не тихий пропуск).
export type HealthResult = { ok: boolean; status: number; url: string; reason?: 'config' };

// Классифицированный вердикт деплоя: red + человекочитаемая причина (в лог/пуш).
export type DeployVerdict = { red: boolean; reason: string };

export type DeployCheckAdapter = {
    // sha коммита мерджа PR в `main`. Fail-closed: бросает, если sha не резолвится
    // (нельзя верифицировать деплой не того коммита).
    mergedShaOf(prNumber: number): string;

    // Ждать завершения деплой-воркфлоу для sha (поллинг с таймаутом). Возвращает
    // исход со статусом completed/timeout/not-found.
    waitForDeployRun(sha: string): DeployOutcome;

    // Проверить здоровье прода (HTTP health-URL с ретраями). `reason:'config'`
    // вместо тихого пропуска при незаданном/кривом URL.
    checkHealth(): HealthResult;

    // Классифицировать исход: GREEN (`red:false`) ТОЛЬКО при зелёном воркфлоу И не
    // явно нездоровом проде; иначе `red:true`. Чистая функция от двух входов.
    classifyOutcome(outcome: DeployOutcome | null, health: HealthResult | null): DeployVerdict;
};

// ---------------------------------------------------------------------------------
// 5. Рантайм кодер-сессии: запуск агента, делающего собственно работу
// ---------------------------------------------------------------------------------
//
// Шов «на чём крутится кодер-сессия». Эталон — Claude CLI: `claude -p` argv,
// permission-mode, `--max-turns`, `--fallback-model`; результат — код возврата +
// собранный stdout+stderr (сканируется на маркер API-лимита, НЕ парсится как JSON —
// сознательно). Специфика провайдера (argv-флаги, формат вывода) живёт ВНУТРИ
// реализации; фаза 6 добавит рантаймы Kimi и OpenAI и AGENTS.md-инструкции для
// не-Claude агентов — они реализуют этот же интерфейс, Claude-путь не меняя.

// Бюджет и модель одной сессии. `maxTurns` — потолок ходов агента; `model`/
// `fallbackModel` провайдер-специфичны (Claude мапит в `--model`/`--fallback-model`;
// `fallbackModel: 'none'`/null — осознанный отказ от фолбэка, honest-стоп).
export type RunOptions = {
    model?: string;
    maxTurns: number;
    fallbackModel?: string | null;
};

// Результат одной сессии: код возврата процесса и объединённый вывод (stdout+stderr).
// Оркестратор сканирует `output` на маркер API-лимита и решает про повтор/ожидание —
// это его политика, не рантайма; рантайм лишь честно отдаёт код и вывод.
export type RunResult = {
    code: number;
    output: string;
};

export type CoderRuntimeAdapter = {
    // Запустить кодер-сессию по промпту в дереве раннера (синхронно). Возвращает код
    // возврата и объединённый вывод. Ожидание API-лимита, ретраи и health туннеля —
    // политика оркестратора вокруг этого вызова, не забота рантайма.
    run(prompt: string, options: RunOptions): RunResult;
};

// ---------------------------------------------------------------------------------
// Набор швов, от которых зависит ядро
// ---------------------------------------------------------------------------------
//
// Единая точка сборки реализаций: #369 соберёт сюда текущие адаптеры (GitHub-форж,
// npm-гейт, Telegram-нотификатор, Actions+health-деплой, Claude-рантайм), выбор —
// через конфиг; ядро зависит только от этих интерфейсов, не от конкретных модулей.
export type RalphAdapters = {
    taskSource: TaskSourceAdapter;
    gate: GateAdapter;
    notifier: NotifierAdapter;
    deployCheck: DeployCheckAdapter;
    coderRuntime: CoderRuntimeAdapter;
};
